export class Project extends BasicModel {
  static type = "project";
  // what every project is expected to carry (glossary: project.md)
  static anatomy = {
    "README.md": "what it is and how to use it",
    "LICENSE": "terms of use",
    "AGENTS.md": "instructions for AI agents (CLAUDE.md imports it)",
    "Taskfile.yml": "procedures: build, test, run",
    "src": "source code",
    "docs": "documentation",
    "tests": "tests",
    ".github": "community files and CI workflows",
  };

  anatomyCheck() {
    const present = [];
    const missing = [];
    for (const part of Object.keys(Project.anatomy)) {
      (new BasicModel(this.file(part)).exists() ? present : missing).push(part);
    }
    return { present, missing };
  }
}

