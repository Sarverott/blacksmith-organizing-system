// not needed to launch; appears with the first recorded event
export class Storylines extends BasicModel {
  static type = "storylines";
  static dirname = "storylines";
  static mandatory = false;
  static children = [Ttystories, Logs, Manifests];
  static descriptors = {
    "metadata.json": (element, context) => ({
      origin: {
        host: context.env?.host ?? null,
        user: context.env?.user ?? null,
        unixusat: context.env?.unixusat ?? Date.now(),
        createdBy: "blacksmith-organizing-system",
      },
    }),
  };

  // one JSON line per event: opening, closing, git hooks, ...
  record(event, context = {}) {
    const entry = { unixusat: Date.now(), host: context.env?.host ?? null, ...event };
    if (!context.dryRun) appendFileSync(this.file("logs", "workshop.jsonl"), JSON.stringify(entry) + "\n");
    return entry;
  }

  ttystoryName(context) {
    return `ttystory-${context.env.host}-${context.env.unixusat}.txt`;
  }
}

export class System extends BasicModel {
  static type = "system";
  static dirname = ".BOS";
  static children = [Setup, Data, Nests, Storylines];
  static descriptors = {
    "workshop.json": (element, context) => context.config ?? {},
    "Taskfile.yaml": () => [
      "# yaml-language-server: $schema=https://taskfile.dev/schema.json",
      "# workshop procedures, generated by BOS bootstrap; edit freely",
      "version: '3'",
      "",
      "vars:",
      `  BOS: node ${CLI}`,
      "",
      "tasks:",
      "  status:",
      "    desc: show the state of this workshop",
      "    cmds: ['{{.BOS}} status']",
      "  open:",
      "    desc: open the workshop (bootstrap missing areas, record opening)",
      "    cmds: ['{{.BOS}} open']",
      "  close:",
      "    desc: close the workshop (capture ttystory, record closing)",
      "    cmds: ['{{.BOS}} close']",
      "",
    ].join("\n"),
  };
}

